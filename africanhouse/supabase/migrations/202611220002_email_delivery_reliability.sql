CREATE OR REPLACE FUNCTION public.claim_email_campaign(p_campaign_id text, p_lease_seconds integer DEFAULT 300)
RETURNS TABLE (claimed boolean, claim_token uuid, total_eligible integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_campaign_id text;
  v_token uuid;
  v_total integer;
  v_snapshot timestamptz;
BEGIN
  UPDATE public.email_campaigns
    SET status = 'sending',
        claim_token = gen_random_uuid(),
        lease_expires_at = now() + make_interval(secs => greatest(30, least(p_lease_seconds, 900))),
        started_at = COALESCE(started_at, now()),
        last_error = NULL
    WHERE id::text = p_campaign_id
      AND (
        status IN ('draft', 'failed', 'partially_failed')
        OR (status = 'scheduled' AND (scheduled_at IS NULL OR scheduled_at <= now()))
        OR (status = 'sending' AND lease_expires_at < now())
      )
    RETURNING id::text, email_campaigns.claim_token, email_campaigns.recipients_snapshotted_at
      INTO v_campaign_id, v_token, v_snapshot;

  IF v_token IS NULL THEN
    RETURN QUERY SELECT false, NULL::uuid, 0;
    RETURN;
  END IF;

  IF v_snapshot IS NULL THEN
    INSERT INTO public.email_deliveries (
      delivery_kind, idempotency_key, campaign_id, subscriber_id, recipient_email, recipient_name, unsubscribe_token
    )
    SELECT
      'campaign',
      'campaign:' || v_campaign_id || ':subscriber:' || s.id::text,
      v_campaign_id,
      s.id::text,
      s.email,
      s.name,
      s.unsubscribe_token
    FROM public.subscribers AS s
    WHERE s.status = 'active'
      AND s.marketing_consent IS TRUE
      AND s.marketing_consent_at IS NOT NULL
      AND s.marketing_consent_source IS NOT NULL
      AND s.marketing_consent_version IS NOT NULL
      AND s.marketing_consent_text IS NOT NULL
    ON CONFLICT DO NOTHING;

    UPDATE public.email_campaigns
      SET recipients_snapshotted_at = now()
      WHERE id::text = v_campaign_id AND email_campaigns.claim_token = v_token;
  END IF;

  SELECT count(*)::integer INTO v_total
  FROM public.email_deliveries d
  WHERE d.delivery_kind = 'campaign' AND d.campaign_id = v_campaign_id;

  UPDATE public.email_campaigns
    SET total_eligible = v_total
    WHERE id::text = v_campaign_id AND email_campaigns.claim_token = v_token;

  RETURN QUERY SELECT true, v_token, v_total;
END;
$$;

CREATE OR REPLACE FUNCTION public.renew_email_campaign_claim(
  p_campaign_id text, p_claim_token uuid, p_lease_seconds integer DEFAULT 300
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE public.email_campaigns
  SET lease_expires_at = now() + make_interval(
    secs => greatest(30, least(p_lease_seconds, 900))
  )
  WHERE id::text = p_campaign_id
    AND status = 'sending'
    AND claim_token = p_claim_token
    AND lease_expires_at > now();

  RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_email_campaign_deliveries(
  p_campaign_id text, p_claim_token uuid, p_limit integer DEFAULT 50, p_lease_seconds integer DEFAULT 180
)
RETURNS TABLE (delivery_id bigint, subscriber_id text, recipient_email text, recipient_name text,
               unsubscribe_token text, idempotency_key text, attempt_count integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE public.email_deliveries d
  SET status = 'skipped', last_error = 'Subscriber is no longer actively consented',
      lease_token = NULL, lease_expires_at = NULL, updated_at = now()
  WHERE d.delivery_kind = 'campaign' AND d.campaign_id = p_campaign_id
    AND d.status IN ('pending', 'failed', 'sending')
    AND (d.status <> 'sending' OR d.lease_expires_at < now())
    AND NOT EXISTS (
      SELECT 1 FROM public.subscribers s
      WHERE s.id::text = d.subscriber_id AND s.status = 'active'
        AND s.unsubscribe_token = d.unsubscribe_token
        AND s.email = d.recipient_email
        AND s.marketing_consent IS TRUE AND s.marketing_consent_at IS NOT NULL
        AND s.marketing_consent_source IS NOT NULL AND s.marketing_consent_version IS NOT NULL
        AND s.marketing_consent_text IS NOT NULL
    );

  RETURN QUERY
  WITH candidates AS (
    SELECT d.id
    FROM public.email_deliveries d
    JOIN public.email_campaigns c ON c.id::text = d.campaign_id
    JOIN public.subscribers s ON s.id::text = d.subscriber_id
    WHERE d.delivery_kind = 'campaign' AND d.campaign_id = p_campaign_id
      AND c.status = 'sending' AND c.claim_token = p_claim_token AND c.lease_expires_at > now()
      AND s.status = 'active' AND s.marketing_consent IS TRUE AND s.marketing_consent_at IS NOT NULL
      AND s.email = d.recipient_email
      AND s.unsubscribe_token = d.unsubscribe_token
      AND s.marketing_consent_source IS NOT NULL AND s.marketing_consent_version IS NOT NULL
      AND s.marketing_consent_text IS NOT NULL
      AND d.attempt_count < 3
      AND (d.status IN ('pending', 'failed') OR (d.status = 'sending' AND d.lease_expires_at < now()))
    ORDER BY d.id
    LIMIT greatest(1, least(p_limit, 50))
    FOR UPDATE OF d SKIP LOCKED
  ), updated AS (
    UPDATE public.email_deliveries d
    SET status = 'sending',
        lease_token = p_claim_token,
        lease_expires_at = now() + make_interval(secs => greatest(30, least(p_lease_seconds, 600))),
        updated_at = now()
    FROM candidates
    WHERE d.id = candidates.id
    RETURNING d.id, d.subscriber_id, d.recipient_email, d.recipient_name,
              d.unsubscribe_token, d.idempotency_key, d.attempt_count
  )
  SELECT updated.id, updated.subscriber_id, updated.recipient_email, updated.recipient_name,
         updated.unsubscribe_token, updated.idempotency_key, updated.attempt_count
  FROM updated;
END;
$$;

CREATE OR REPLACE FUNCTION public.begin_email_delivery_attempt(p_delivery_id bigint, p_claim_token uuid)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_attempt_count integer;
BEGIN
  UPDATE public.email_deliveries d
    SET attempt_count = d.attempt_count + 1, updated_at = now()
    FROM public.subscribers s
    WHERE d.id = p_delivery_id AND d.status = 'sending'
      AND d.lease_token = p_claim_token AND d.lease_expires_at > now()
      AND d.attempt_count < 3
      AND s.id::text = d.subscriber_id AND s.status = 'active'
      AND s.email = d.recipient_email
      AND s.unsubscribe_token = d.unsubscribe_token
      AND s.marketing_consent IS TRUE AND s.marketing_consent_at IS NOT NULL
      AND s.marketing_consent_source IS NOT NULL AND s.marketing_consent_version IS NOT NULL
      AND s.marketing_consent_text IS NOT NULL
    RETURNING d.attempt_count INTO v_attempt_count;
  RETURN v_attempt_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.refresh_email_campaign_stats(p_campaign_id text, p_claim_token uuid)
RETURNS TABLE (campaign_status text, total_eligible integer, attempted_count integer, sent_count integer,
               delivered_count integer, failed_count integer, pending_count integer, skipped_count integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_total integer;
  v_attempted integer;
  v_sent integer;
  v_delivered integer;
  v_failed integer;
  v_pending integer;
  v_skipped integer;
  v_status text;
BEGIN
  SELECT count(*)::integer,
         count(*) FILTER (WHERE attempt_count > 0)::integer,
         count(*) FILTER (WHERE sent_at IS NOT NULL)::integer,
         count(*) FILTER (WHERE status = 'delivered')::integer,
         count(*) FILTER (WHERE status IN ('failed', 'bounced'))::integer,
         count(*) FILTER (WHERE status IN ('pending', 'sending'))::integer,
         count(*) FILTER (WHERE status = 'skipped')::integer
    INTO v_total, v_attempted, v_sent, v_delivered, v_failed, v_pending, v_skipped
    FROM public.email_deliveries
    WHERE delivery_kind = 'campaign' AND campaign_id = p_campaign_id;

  IF v_pending > 0 THEN
    v_status := 'sending';
  ELSIF v_total = 0 OR v_sent = 0 THEN
    v_status := 'failed';
  ELSIF v_failed > 0 AND v_sent > 0 THEN
    v_status := 'partially_failed';
  ELSIF v_failed > 0 THEN
    v_status := 'failed';
  ELSE
    v_status := 'sent';
  END IF;

  UPDATE public.email_campaigns
    SET total_eligible = v_total,
        attempted_count = v_attempted,
        sent_count = v_sent,
        delivered_count = v_delivered,
        failed_count = v_failed,
        pending_count = v_pending,
        skipped_count = v_skipped,
        recipient_count = v_sent,
        status = v_status,
        last_error = CASE WHEN v_total = 0 OR v_sent = 0 THEN 'No messages were accepted by Resend' ELSE NULL END,
        sent_at = CASE WHEN v_status IN ('sent', 'partially_failed', 'failed') THEN COALESCE(sent_at, now()) ELSE sent_at END,
        claim_token = CASE WHEN v_pending = 0 THEN NULL ELSE claim_token END,
        lease_expires_at = CASE WHEN v_pending = 0 THEN NULL ELSE lease_expires_at END
    WHERE id::text = p_campaign_id AND claim_token = p_claim_token;

  IF NOT FOUND THEN RAISE EXCEPTION 'Campaign claim was lost while refreshing delivery statistics'; END IF;
  RETURN QUERY SELECT v_status, v_total, v_attempted, v_sent, v_delivered, v_failed, v_pending, v_skipped;
END;
$$;


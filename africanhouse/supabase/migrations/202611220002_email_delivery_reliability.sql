CREATE OR REPLACE FUNCTION public.guard_email_campaign_updates()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN
    IF OLD.recipients_snapshotted_at IS NOT NULL AND (
      NEW.name IS DISTINCT FROM OLD.name OR
      NEW.subject IS DISTINCT FROM OLD.subject OR
      NEW.preview_text IS DISTINCT FROM OLD.preview_text OR
      NEW.template_type IS DISTINCT FROM OLD.template_type OR
      NEW.body_html IS DISTINCT FROM OLD.body_html
    ) THEN
      RAISE EXCEPTION 'Campaign content cannot change after recipient snapshot';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status
       OR NEW.total_eligible IS DISTINCT FROM OLD.total_eligible
       OR NEW.attempted_count IS DISTINCT FROM OLD.attempted_count
       OR NEW.sent_count IS DISTINCT FROM OLD.sent_count
       OR NEW.delivered_count IS DISTINCT FROM OLD.delivered_count
       OR NEW.failed_count IS DISTINCT FROM OLD.failed_count
       OR NEW.pending_count IS DISTINCT FROM OLD.pending_count
       OR NEW.skipped_count IS DISTINCT FROM OLD.skipped_count
      OR NEW.recipient_count IS DISTINCT FROM OLD.recipient_count
      OR NEW.sent_at IS DISTINCT FROM OLD.sent_at
      OR NEW.started_at IS DISTINCT FROM OLD.started_at
      OR NEW.last_error IS DISTINCT FROM OLD.last_error
       OR NEW.claim_token IS DISTINCT FROM OLD.claim_token
       OR NEW.lease_expires_at IS DISTINCT FROM OLD.lease_expires_at
       OR NEW.recipients_snapshotted_at IS DISTINCT FROM OLD.recipients_snapshotted_at THEN
      RAISE EXCEPTION 'Campaign delivery state is managed by trusted server functions';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

